const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  // Language locked to English for now
  const [language, setLanguageState] = useState('en');

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, 'en');
    } catch (e) {}
  }, []);

  const setLanguage = (lang) => {
    // Language change disabled for now - keep English
    setLanguageState('en');
    try {
      localStorage.setItem(STORAGE_KEY, 'en');
    } catch (e) {}
  };

  /**
   * Helper translation function supporting dot-notation keys: e.g. t('nav.dashboard')
   */
  const t = (path, fallback = '') => {
    if (!path) return fallback;
    const keys = path.split('.');
    let current = TRANSLATIONS[language] || TRANSLATIONS.en;
    for (const key of keys) {
      if (current && typeof current === 'object' && key in current) {
        current = current[key];
      } else {
        // Fallback to English
        let eng = TRANSLATIONS.en;
        for (const k of keys) {
          if (eng && typeof eng === 'object' && k in eng) {
            eng = eng[k];
          } else {
            return fallback || path;
          }
        }
        return typeof eng === 'string' ? eng : (fallback || path);
      }
    }
    return typeof current === 'string' ? current : (fallback || path);
  };

  const currentLangMeta = useMemo(() => {
    return LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];
  }, [language]);

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        languages: LANGUAGES,
        currentLangMeta,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

export default LanguageContext;
