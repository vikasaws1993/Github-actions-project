export type TranslationKey = keyof typeof translations['mr'];

export const NEXT_LANGUAGE_MAP: Record<AppLanguage, NextLanguageConfig> = {
  mr: { code: 'en', label: 'English' },
  en: { code: 'hi', label: 'हिंदी' },
  hi: { code: 'mr', label: 'मराठी' },
};

export interface LanguageContextType {
  language: AppLanguage;
  appLanguage: AppLanguage;
  setLanguage: (lang: AppLanguage) => Promise<void>;
  setAppLanguage: (lang: AppLanguage) => Promise<void>;
  toggleNextLanguage: () => Promise<void>;
  t: (key: TranslationKey) => string;
  currentOption: LanguageOption;
  nextOption: NextLanguageConfig;
}

const LANGUAGE_STORAGE_KEY = 'AROGYAMITRA_APP_LANG';

const LanguageContext = createContext<LanguageContextType>({
  language: 'mr',
  appLanguage: 'mr',
  setLanguage: async () => { },
  setAppLanguage: async () => { },
  toggleNextLanguage: async () => { },
  t: (key) => translations.mr[key] || '',
  currentOption: LANGUAGE_OPTIONS[0],
  nextOption: NEXT_LANGUAGE_MAP.mr,
});

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<AppLanguage>('mr');

  useEffect(() => {
    loadLanguage();
  }, []);

  const loadLanguage = async () => {
    try {
      const saved = await storage.getItem<AppLanguage>(LANGUAGE_STORAGE_KEY);
      if (saved && (saved === 'mr' || saved === 'en' || saved === 'hi')) {
        setLanguageState(saved);
        setApiClientLanguage(saved);
      }
    } catch {
      // fallback to default 'mr'
    }
  };

  const setLanguage = async (newLang: AppLanguage) => {
    setLanguageState(newLang);
    setApiClientLanguage(newLang);
    try {
      await storage.setItem(LANGUAGE_STORAGE_KEY, newLang);
    } catch {
      // ignore
    }
  };

  const setAppLanguage = setLanguage;

  const toggleNextLanguage = async () => {
    const next = NEXT_LANGUAGE_MAP[language] || NEXT_LANGUAGE_MAP.mr;
    await setLanguage(next.code);
  };

  const t = (key: TranslationKey): string => {
    const langDict = translations[language] || translations.mr;
    return langDict[key] || translations.mr[key] || '';
  };

  const currentOption =
    LANGUAGE_OPTIONS.find((opt) => opt.code === language) || LANGUAGE_OPTIONS[0];

  const nextOption = NEXT_LANGUAGE_MAP[language] || NEXT_LANGUAGE_MAP.mr;

  return (
    <LanguageContext.Provider
      value={{
        language,
        appLanguage: language,
        setLanguage,
        setAppLanguage,
        toggleNextLanguage,
        t,
        currentOption,
        nextOption,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

